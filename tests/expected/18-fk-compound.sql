
CREATE DATABASE `demo` CHARACTER SET utf8mb4;

CREATE TABLE `parent` (
  `id` int NOT NULL AUTO_INCREMENT PRIMARY KEY
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `child` (
  `id` int NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `parent_id` int NOT NULL,
  FOREIGN KEY (`parent_id`) REFERENCES `parent`(`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
